/**
 * Regenerates lib/calendly-availability.json from the live Calendly account.
 *
 * The booking panel publishes these hours as crawlable text, so they must match
 * what Calendly will actually offer. Run this after changing working hours in
 * the Calendly dashboard:
 *
 *   npm run sync:availability
 *
 * Reads CALENDLY_API_KEY from the environment or from the repo-root .env. The
 * token is org-owner scoped, so it stays server-side: this writes a data file
 * at development time and is never bundled.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const API = "https://api.calendly.com";
const OUT = resolve(import.meta.dirname, "../lib/calendly-availability.json");

function token() {
  if (process.env.CALENDLY_API_KEY) return process.env.CALENDLY_API_KEY;

  // Walk up looking for the gitignored .env. In a git worktree the checkout
  // sits several levels below the main one, which is where .env actually lives.
  let dir = import.meta.dirname;
  for (let depth = 0; depth < 8; depth += 1) {
    try {
      const match = readFileSync(resolve(dir, ".env"), "utf8").match(
        /^CALENDLY_API_KEY=(.+)$/m,
      );
      if (match) return match[1].trim();
    } catch {
      // No .env at this level; keep climbing.
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }

  throw new Error("CALENDLY_API_KEY not found in the environment or any .env");
}

async function get(url, key) {
  const response = await fetch(url, { headers: { Authorization: `Bearer ${key}` } });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} for ${url}`);
  }
  return response.json();
}

const key = token();
const { resource: user } = await get(`${API}/users/me`, key);

const [schedule] = (
  await get(`${API}/user_availability_schedules?user=${user.uri}`, key)
).collection.filter((entry) => entry.default);

if (!schedule) throw new Error("No default availability schedule on the account");

const [eventType] = (
  await get(`${API}/event_types?user=${user.uri}&active=true`, key)
).collection;

if (!eventType) throw new Error("No active event type on the account");

// `wday` rules are the recurring weekly pattern. Date-specific overrides are
// deliberately dropped: they expire, and stale hours on the page are worse than
// no hours at all.
const days = Object.fromEntries(
  schedule.rules
    .filter((rule) => rule.type === "wday")
    .map((rule) => [
      rule.wday,
      rule.intervals.map(({ from, to }) => ({ from, to })),
    ]),
);

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      $comment: "Generated by npm run sync:availability. Do not edit by hand.",
      timezone: schedule.timezone ?? user.timezone,
      durationMinutes: eventType.duration,
      days,
    },
    null,
    2,
  )}\n`,
);

console.log(`Wrote ${OUT}`);
for (const [day, intervals] of Object.entries(days)) {
  const text = intervals.map((i) => `${i.from}-${i.to}`).join(", ") || "closed";
  console.log(`  ${day.padEnd(10)} ${text}`);
}
